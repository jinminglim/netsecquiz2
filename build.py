#!/usr/bin/env python3
"""Build self-contained pages.

Reads the page templates in src/ (which reference ../assets/*.css|js) and writes
index.html and guide.html at the repo root with every stylesheet and script
inlined, so each page works on its own: opened from a download, a file preview,
or GitHub Pages.

Usage:  python3 build.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
PAGES = ["index.html", "guide.html"]

LINK_RE = re.compile(r'<link rel="stylesheet" href="\.\./(assets/[^"]+\.css)">')
SCRIPT_RE = re.compile(r'<script src="\.\./(assets/[^"]+\.js)"></script>')


def read_asset(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def build(page: str) -> None:
    html = (SRC / page).read_text(encoding="utf-8")

    def inline_css(m: re.Match) -> str:
        css = read_asset(m.group(1))
        assert "</style" not in css.lower(), m.group(1)
        return f"<style>/* {m.group(1)} */\n{css}\n</style>"

    def inline_js(m: re.Match) -> str:
        js = read_asset(m.group(1)).replace("</script", "<\\/script")
        return f"<script>/* {m.group(1)} */\n{js}\n</script>"

    html, n_css = LINK_RE.subn(inline_css, html)
    html, n_js = SCRIPT_RE.subn(inline_js, html)
    if "../assets/" in html:
        raise SystemExit(f"{page}: un-inlined asset reference left over")
    banner = "<!-- GENERATED by build.py from src/" + page + " + assets/ — edit those, then re-run build.py -->"
    doctype, rest = html.split("\n", 1)
    assert doctype.lower().startswith("<!doctype"), page
    (ROOT / page).write_text(doctype + "\n" + banner + "\n" + rest, encoding="utf-8")
    print(f"{page}: inlined {n_css} stylesheet(s), {n_js} script(s), {len(html) // 1024} KB")


if __name__ == "__main__":
    for p in PAGES:
        build(p)
